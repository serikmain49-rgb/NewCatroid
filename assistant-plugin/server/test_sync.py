import json,pathlib,sys,tempfile,unittest,copy
from server import Store
from sync_store import accept_sync,digest
fixture=json.loads(pathlib.Path(sys.argv[1]).read_text()) if len(sys.argv)>1 else None
class SyncTests(unittest.TestCase):
 def setUp(self):
  self.tmp=tempfile.TemporaryDirectory();self.store=Store(self.tmp.name)
  self.full=copy.deepcopy(fixture['full']);self.delta=copy.deepcopy(fixture['delta'])
 def tearDown(self):self.tmp.cleanup()
 def test_full_delta_and_restart(self):
  self.assertTrue(accept_sync(self.store,self.full)['ok']);reply=accept_sync(self.store,self.delta)
  self.assertEqual(reply['mode'],'delta');self.assertLess(reply['bytes_received'],reply['reconstructed_bytes']//20)
  self.assertEqual(digest(self.store.state['code_xml']),self.delta['target_sha256'])
  s=Store(self.tmp.name);same={**self.delta,'base_sha256':self.delta['target_sha256'],'changed':{}}
  self.assertEqual(accept_sync(s,same)['parts_sent'],0)
 def test_missing_base(self):self.assertEqual(accept_sync(self.store,self.delta)['code'],'FULL_EXPORT_REQUIRED')
 def test_corruption_atomic(self):
  accept_sync(self.store,self.full);old=self.store.state['project']['base_sha256'];bad=copy.deepcopy(self.delta);key=next(iter(bad['changed']));bad['changed'][key]='broken'
  with self.assertRaisesRegex(ValueError,'FRAGMENT_HASH_MISMATCH'):accept_sync(self.store,bad)
  self.assertEqual(self.store.state['project']['base_sha256'],old)
 def test_expected_project(self):
  accept_sync(self.store,self.full);rid=self.store.request()['request_id'];self.assertEqual(self.store.pending['expected_project_id'],self.full['project_id'])
  bad={**self.delta,'request_id':rid,'project_id':'b'*64}
  with self.assertRaisesRegex(ValueError,'WRONG_PROJECT'):accept_sync(self.store,bad)
 def test_patch_identity(self):
  accept_sync(self.store,self.full);p={'format':1,'id':'wrong','title':'identity','project':self.full['project'],'project_id':'b'*64,'request_id':self.full['request_id'],'base_sha256':self.full['target_sha256'],'operations':[{'op':'scene.create','scene':'new'}]}
  with self.assertRaisesRegex(ValueError,'WRONG_PROJECT'):self.store.submit(p)
if __name__=='__main__':
 if fixture is None:raise SystemExit('Provide the sync-fixtures.json generated by checks/test_bridge.py')
 unittest.main(argv=[sys.argv[0]],verbosity=2)
